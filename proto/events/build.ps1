<#
.SYNOPSIS
  Builds an events dev copy of the faction (dev only): the real module path for the Lantern Festival and the Great
  Flowering, with their data generated by the catalogue, plus a separate probe mod.
.DESCRIPTION
  Never depends on the shared install's switches, never touches it or the Mods folder.
    1. The catalogue is copied to a scratch folder with rules.toml [modules] Festival, Flowering and Water switched on (the
       Kitchen and rice flour, needed for seed cakes, are gated with Water), and generated there (src/gen/generate.py
       --catalogue/--out): exactly the data the content lane ships when it flips those switches.
    2. proto/foundation/build.ps1 -Name <Name> builds a full copy of the installed faction with the current src/code
       (bootstrap, Specs, Core and every module in modules.txt, Festival and Flowering included: they load through the
       bootstrap's API check like any shipped module). Manifest Id JigglyPanda.PandabornFactionsDev.
    3. The generated data is laid over the copy, the meshes of every model it adopts are copied in (as assemble does), and
       the -Variant fragments (*.fragment.json merged, other files copied; default proto/events/variants/test: fast
       Flowering timings and the lumberjack as a stand-in pump crew) are applied.
    4. The probe (proto/events/src) is built as its own mod, E:\PandabornDev\build\proto\events-probe (requires the copy).
  Run: tools\run_game_test.ps1 -DisableMods JigglyPanda.PandabornFactions
         -ExtraMods E:\PandabornDev\build\proto\<Name>,E:\PandabornDev\build\proto\events-probe ...
  When the catalogue ships Festival and Flowering itself, step 1 is the same data: nothing here carries data of its own.
#>
[CmdletBinding()]
param(
    [string]$Name = 'pbevents',
    [string]$DevSwitch = '',
    [string[]]$Variant = @(),
    [switch]$NoVariant,
    # keep the existing probe mod (when another copy is built while a run may be using the probe)
    [switch]$NoProbe,
    # replace the copy's pandabornplants bundle with a newer plant-lane build (e.g. E:\PandabornDev\build\plants\AssetBundles)
    [string]$PlantBundles = '',
    # replace the copy's pandabornattachments bundle with another build (e.g. E:\PandabornDev\build\characters\attachments)
    [string]$AttachmentBundles = '',
    [string]$Python = 'E:\PandabornDev\tools\venv\Scripts\python.exe',
    # the generator needs Python 3.11+ (tomllib), as tools\pandaborn.ps1 finds it
    [string]$GenPython = 'python'
)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$repo = (Resolve-Path (Join-Path $here '..\..')).Path
$out = Join-Path 'E:\PandabornDev\build\proto' $Name
$catDir = 'E:\PandabornDev\build\proto\events-catalogue'
$genDir = 'E:\PandabornDev\build\proto\events-gen\PandabornFactions'
$Variant = @($Variant | ForEach-Object { $_ -split ',' } | Where-Object { $_ })   # 'a,b' through -File
if (-not $Variant -and -not $NoVariant) { $Variant = @(Join-Path $here 'variants\test') }

# 1. the catalogue with the events switched on
if (Test-Path $catDir) { Remove-Item -LiteralPath $catDir -Recurse -Force }
New-Item -ItemType Directory -Force $catDir | Out-Null
Copy-Item -LiteralPath (Join-Path $repo 'catalogue') -Destination $catDir -Recurse
$rules = Join-Path $catDir 'catalogue\rules.toml'
$text = [IO.File]::ReadAllText($rules)
foreach ($m in 'Festival', 'Flowering', 'Water') { $text = [regex]::Replace($text, "(?m)^$m\s*=\s*false", "$m = true") }
[IO.File]::WriteAllText($rules, $text, (New-Object Text.UTF8Encoding($false)))
& $GenPython (Join-Path $repo 'src\gen\generate.py') --catalogue (Join-Path $catDir 'catalogue') --out $genDir --quiet
if ($LASTEXITCODE -ne 0) { throw "generate failed ($LASTEXITCODE)" }

# 2. the dev copy with the current code
& (Join-Path $repo 'proto\foundation\build.ps1') -Name $Name -DevSwitch $DevSwitch
if (-not $?) { throw 'foundation copy failed' }

# 3. data, meshes, fragments
$n = 0
foreach ($f in Get-ChildItem -LiteralPath $genDir -Recurse -File) {
    $to = Join-Path $out $f.FullName.Substring($genDir.Length + 1)
    New-Item -ItemType Directory -Force (Split-Path $to -Parent) | Out-Null
    Copy-Item -LiteralPath $f.FullName -Destination $to -Force; $n++
}
$meshes = 0
$mm = Get-Content -LiteralPath "$genDir.models.json" -Raw | ConvertFrom-Json
foreach ($p in $mm.files.PSObject.Properties) {
    $to = Join-Path $out ($p.Name.Replace('/', '\'))
    if (Test-Path -LiteralPath $to) { continue }
    if (-not (Test-Path -LiteralPath $p.Value)) { throw "model mesh missing (run the models stage): $($p.Value)" }
    New-Item -ItemType Directory -Force (Split-Path $to -Parent) | Out-Null
    Copy-Item -LiteralPath $p.Value -Destination $to; $meshes++
}
# character meshes the generated data names but the installed copy lacks (assemble copies them from the characters build)
foreach ($f in Get-ChildItem -LiteralPath (Join-Path $genDir 'Characters\Pandaborn') -Filter '*.blueprint.json' -ErrorAction SilentlyContinue) {
    foreach ($m in [regex]::Matches([IO.File]::ReadAllText($f.FullName), '"Model":\s*"(Characters/Pandaborn/[^"]+)"')) {
        $to = Join-Path $out ($m.Groups[1].Value.Replace('/', '\') + '.timbermesh')
        $from = Join-Path 'E:\PandabornDev\build\characters\out' ((Split-Path $to -Leaf))
        if (-not (Test-Path $to) -and (Test-Path $from)) { Copy-Item -LiteralPath $from -Destination $to; $meshes++ }
    }
}
# asset bundles the generated data needs but the copy lacks (e.g. pandabornattachments: the characters' hats and baskets),
# from the last full build, never renamed
$bundleSrc = 'E:\PandabornDev\build\PandabornFactions\AssetBundles'
foreach ($b in Get-ChildItem -LiteralPath $bundleSrc -File -Filter 'pandaborn*' -ErrorAction SilentlyContinue) {
    if ($b.Extension) { continue }
    $to = Join-Path $out "AssetBundles\$($b.Name)"
    if (-not (Test-Path -LiteralPath $to)) { Copy-Item -LiteralPath $b.FullName -Destination $to; Write-Host "bundle $($b.Name) from the last full build" }
}
foreach ($frag in $Variant) {
    $frag = (Resolve-Path $frag).Path
    foreach ($f in Get-ChildItem -LiteralPath $frag -Recurse -File) {
        $rel = $f.FullName.Substring($frag.Length + 1)
        $to = Join-Path $out ($rel -replace '\.fragment\.json$', '.json')
        New-Item -ItemType Directory -Force (Split-Path $to -Parent) | Out-Null
        if ($rel -like '*.fragment.json') {
            & $Python -I (Join-Path $repo 'proto\foundation\tools\merge.py') $to $f.FullName
            if ($LASTEXITCODE -ne 0) { throw "merging $rel failed" }
        } else { Copy-Item -LiteralPath $f.FullName -Destination $to -Force }
    }
}
if ($PlantBundles) {
    foreach ($b in 'pandabornplants_win', 'pandabornplants_mac') {
        $from = Join-Path $PlantBundles $b; $to = Join-Path $out "AssetBundles\$b"
        if (-not (Test-Path $from)) { continue }
        if (Test-Path $to) { Remove-Item -LiteralPath $to -Force }   # never write through a hard link into the install
        Copy-Item -LiteralPath $from -Destination $to
    }
    Write-Host "plant bundle from $PlantBundles" -ForegroundColor Yellow
}
if ($AttachmentBundles) {
    foreach ($b in 'pandabornattachments_win', 'pandabornattachments_mac') {
        $from = Join-Path $AttachmentBundles $b; $to = Join-Path $out "AssetBundles\$b"
        if (-not (Test-Path $from)) { continue }
        if (Test-Path $to) { Remove-Item -LiteralPath $to -Force }
        Copy-Item -LiteralPath $from -Destination $to
    }
    Write-Host "attachments bundle from $AttachmentBundles" -ForegroundColor Yellow
}
Write-Host "events data: $n generated files, $meshes model meshes, variants: $($Variant -join ', ')" -ForegroundColor Green

# 4. the probe mod, compiled against the copy's own assemblies
if ($NoProbe) { Write-Host "Built $out (probe kept)" -ForegroundColor Green; return }
$probeOut = 'E:\PandabornDev\build\proto\events-probe'
$refDir = 'E:\PandabornDev\build\obj\proto-events-ref'
foreach ($d in $probeOut, $refDir) { if (Test-Path $d) { Remove-Item -LiteralPath $d -Recurse -Force }; New-Item -ItemType Directory -Force $d | Out-Null }
foreach ($b in 'Scripts\Pandaborn.Core', 'Scripts\Pandaborn.Specs', 'Modules\Pandaborn.Festival', 'Modules\Pandaborn.Flowering') {
    Copy-Item -LiteralPath (Join-Path $out "$b.bin") -Destination (Join-Path $refDir ((Split-Path $b -Leaf) + '.dll'))
}
$log = & dotnet build (Join-Path $here 'src\PandabornProtoEvents.csproj') -c Release -v q --nologo "-p:ModOut=$probeOut" "-p:RefDir=$refDir" 2>&1
if ($LASTEXITCODE -ne 0) { $log | ForEach-Object { Write-Host $_ -ForegroundColor Red }; throw 'probe build failed' }
$manifest = [ordered]@{
    Name = 'Pandaborn - events probe (dev only)'; Version = '0.0.1'; Id = 'JigglyPanda.PandabornProtoEvents'; MinimumGameVersion = '1.1.0.0'
    Description = 'Development-only test probe for the Lantern Festival and the Great Flowering. Never shipped. Art and code are AI-generated.'
    RequiredMods = @([ordered]@{ Id = 'JigglyPanda.PandabornFactionsDev' }); OptionalMods = @()
}
[IO.File]::WriteAllText((Join-Path $probeOut 'manifest.json'), ($manifest | ConvertTo-Json -Depth 4), (New-Object Text.UTF8Encoding($false)))
Write-Host "Built $out and $probeOut" -ForegroundColor Green
