// Pandaborn.ApiScan: writes a module's required-API list from its compiled assembly.
//
//   dotnet Pandaborn.ApiScan.dll <module.dll> <out.api.txt> [--feature <FEATURE.md>] [--title <text>] [--ref <game Managed folder>]
//
// The list holds every type, method and field the module references in a game assembly (Timberborn.*, Bindito.*,
// Unity*), one per line, tab-separated:
//   T <assembly> <type>
//   M <assembly> <type> <name> <generic arity> <parameter types joined by ';'> <return type>
//   F <assembly> <type> <name> <field type>
//   V <assembly> <type> <C|I> <members joined by '|'>
//                                  (a game class the module derives from, or a game interface it implements, with every
//                                  abstract member it had at build time as name~arity~parameters~return type. A member
//                                  the running game has and this list lacks is one the module cannot implement, so the
//                                  module must not load. Needs --ref to read the game assemblies.)
//   R <assembly>                   (another Pandaborn assembly this module references; it must be loaded first)
//   D <spec class name>            (a ComponentSpec subclass this module defines; checked for name clashes)
// A call binds to name, parameters AND return type, so a getter whose type changed in a game update is as missing as a
// removed one: the return and field types are part of the line.
// Type names: namespace-qualified, nested types with '+', generic instances as Name`1<Arg>, generic parameters !n (type)
// and !!n (method), arrays T[], by-ref T&, pointers T*. Pandaborn.Bootstrap formats runtime types the same way and
// resolves every line before it loads the module. The same list is written, grouped, into FEATURE.md between the
// markers <!-- api:begin --> and <!-- api:end -->, so a game update shows up as a diff.
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Text.RegularExpressions;

internal static class Program
{
    private static readonly Regex GameAssembly = new Regex(@"^(Timberborn\.|Bindito\.|Unity)", RegexOptions.Compiled);

    private static int Main(string[] args)
    {
        if (args.Length < 2)
        {
            Console.Error.WriteLine("usage: Pandaborn.ApiScan <module.dll> <out.api.txt> [--feature <FEATURE.md>] [--title <text>] [--ref <game Managed folder>]");
            return 2;
        }
        string feature = null, title = null, refDir = null;
        for (int i = 2; i < args.Length - 1; i++)
        {
            if (args[i] == "--feature") feature = args[++i];
            else if (args[i] == "--title") title = args[++i];
            else if (args[i] == "--ref") refDir = args[++i];
        }
        try
        {
            var lines = Scan(args[0], refDir);
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[1])));
            var header = "# Required game API of " + Path.GetFileNameWithoutExtension(args[0]) + " (generated by Pandaborn.ApiScan; do not edit)\n";
            WriteIfChanged(args[1], header + string.Join("\n", lines) + "\n");
            if (feature != null) WriteFeature(feature, title ?? Path.GetFileNameWithoutExtension(args[0]), lines);
            Console.WriteLine($"ApiScan: {Path.GetFileName(args[0])}: {lines.Count(l => l[0] == 'T')} types, {lines.Count(l => l[0] == 'M')} methods, "
                              + $"{lines.Count(l => l[0] == 'F')} fields, {lines.Count(l => l[0] == 'V')} base types and interfaces, "
                              + $"{lines.Count(l => l[0] == 'D')} spec classes");
            return 0;
        }
        catch (Exception e)
        {
            Console.Error.WriteLine("ApiScan failed: " + e);
            return 1;
        }
    }

    private static void WriteIfChanged(string path, string text)
    {
        if (File.Exists(path) && File.ReadAllText(path) == text) return;
        File.WriteAllText(path, text, new UTF8Encoding(false));
    }

    private static List<string> Scan(string path, string refDir)
    {
        using var stream = File.OpenRead(path);
        using var pe = new PEReader(stream);
        var md = pe.GetMetadataReader();
        var names = new Names(md);
        var result = new SortedSet<string>(StringComparer.Ordinal);

        foreach (var h in md.TypeReferences)
        {
            var asm = names.AssemblyOf(h);
            if (asm != null && GameAssembly.IsMatch(asm)) result.Add($"T\t{asm}\t{names.TypeRefName(h)}");
        }

        var provider = new SignatureNames(names);
        foreach (var h in md.MemberReferences)
        {
            var member = md.GetMemberReference(h);
            if (!names.TryGetParent(member.Parent, out string asm, out string type)) continue;
            if (!GameAssembly.IsMatch(asm)) continue;
            string name = md.GetString(member.Name);
            if (member.GetKind() == MemberReferenceKind.Field)
            {
                result.Add($"F\t{asm}\t{type}\t{name}\t{member.DecodeFieldSignature(provider, null)}");
                continue;
            }
            var sig = member.DecodeMethodSignature(provider, null);
            result.Add($"M\t{asm}\t{type}\t{name}\t{sig.GenericParameterCount}\t{string.Join(";", sig.ParameterTypes)}\t{sig.ReturnType}");
        }

        foreach (var h in md.TypeDefinitions)
            if (names.IsComponentSpec(h)) result.Add("D\t" + md.GetString(md.GetTypeDefinition(h).Name));

        // other Pandaborn assemblies this module needs (Specs, Core; a feature module that names another feature module
        // gets a line too, and stays off whenever that one is off, instead of failing to load its types)
        foreach (var h in md.AssemblyReferences)
        {
            string name = md.GetString(md.GetAssemblyReference(h).Name);
            if (name.StartsWith("Pandaborn.", StringComparison.Ordinal)) result.Add("R\t" + name);
        }

        // game classes the module derives from and game interfaces it implements, with their abstract members
        if (refDir != null)
        {
            using var game = new GameAssemblies(refDir);
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var h in md.TypeDefinitions)
            {
                var def = md.GetTypeDefinition(h);
                if (names.TryGetParent(def.BaseType, out string asm, out string type) && GameAssembly.IsMatch(asm) && seen.Add("C|" + asm + "|" + type))
                    result.Add($"V\t{asm}\t{type}\tC\t{string.Join("|", game.AbstractMembers(asm, type, false))}");
                foreach (var ih in def.GetInterfaceImplementations())
                    if (names.TryGetParent(md.GetInterfaceImplementation(ih).Interface, out asm, out type) && GameAssembly.IsMatch(asm) && seen.Add("I|" + asm + "|" + type))
                        result.Add($"V\t{asm}\t{type}\tI\t{string.Join("|", game.AbstractMembers(asm, type, true))}");
            }
        }
        return result.ToList();
    }

    /// <summary>
    /// Reads the game's own assemblies (the Managed folder) to list the abstract members of a class and its bases, or the
    /// members of an interface and the interfaces it inherits. Only game assemblies are followed: what a System type
    /// asks for does not change with a game update.
    /// </summary>
    private sealed class GameAssemblies : IDisposable
    {
        private readonly string _dir;
        private readonly Dictionary<string, (PEReader Pe, MetadataReader Md, Names Names)> _open = new Dictionary<string, (PEReader, MetadataReader, Names)>(StringComparer.Ordinal);

        public GameAssemblies(string dir) { _dir = dir; }

        public void Dispose()
        {
            foreach (var o in _open.Values) o.Pe?.Dispose();
        }

        private (PEReader Pe, MetadataReader Md, Names Names) Open(string asm)
        {
            if (_open.TryGetValue(asm, out var o)) return o;
            string file = Path.Combine(_dir, asm + ".dll");
            if (!File.Exists(file)) throw new FileNotFoundException("game assembly not found for the base-type scan: " + file);
            var pe = new PEReader(File.OpenRead(file));
            var md = pe.GetMetadataReader();
            return _open[asm] = (pe, md, new Names(md));
        }

        public List<string> AbstractMembers(string asm, string type, bool isInterface)
        {
            var result = new SortedSet<string>(StringComparer.Ordinal);
            Collect(asm, type, isInterface, result, new HashSet<string>(StringComparer.Ordinal));
            return result.ToList();
        }

        private void Collect(string asm, string type, bool isInterface, SortedSet<string> result, HashSet<string> visited)
        {
            if (!GameAssembly.IsMatch(asm) || !visited.Add(asm + "|" + type)) return;
            var (_, md, names) = Open(asm);
            TypeDefinitionHandle found = default;
            foreach (var h in md.TypeDefinitions)
                if (names.TypeDefName(h) == type) { found = h; break; }
            if (found.IsNil) throw new InvalidOperationException("type " + type + " not found in " + asm + " (forwarded?)");
            var def = md.GetTypeDefinition(found);
            var provider = new SignatureNames(names);
            foreach (var mh in def.GetMethods())
            {
                var m = md.GetMethodDefinition(mh);
                if ((m.Attributes & System.Reflection.MethodAttributes.Abstract) == 0) continue;
                var sig = m.DecodeSignature(provider, null);
                result.Add(md.GetString(m.Name) + "~" + sig.GenericParameterCount + "~" + string.Join(";", sig.ParameterTypes) + "~" + sig.ReturnType);
            }
            if (isInterface)
            {
                foreach (var ih in def.GetInterfaceImplementations())
                    if (Target(md, names, asm, md.GetInterfaceImplementation(ih).Interface, out string a, out string t)) Collect(a, t, true, result, visited);
            }
            else if (Target(md, names, asm, def.BaseType, out string a, out string t)) Collect(a, t, false, result, visited);
        }

        /// <summary>The assembly and name of a base type or interface named from inside a game assembly.</summary>
        private static bool Target(MetadataReader md, Names names, string asm, EntityHandle handle, out string targetAsm, out string type)
        {
            targetAsm = null; type = null;
            if (handle.IsNil) return false;
            if (handle.Kind == HandleKind.TypeDefinition)
            {
                targetAsm = asm; type = names.TypeDefName((TypeDefinitionHandle)handle);
                return true;
            }
            if (handle.Kind == HandleKind.TypeSpecification)
            {
                var reader = md.GetBlobReader(md.GetTypeSpecification((TypeSpecificationHandle)handle).Signature);
                if (reader.ReadSignatureTypeCode() != SignatureTypeCode.GenericTypeInstance) return false;
                reader.ReadCompressedInteger();           // CLASS or VALUETYPE
                var generic = reader.ReadTypeHandle();
                if (generic.Kind == HandleKind.TypeDefinition)
                {
                    targetAsm = asm; type = names.TypeDefName((TypeDefinitionHandle)generic);
                    return true;
                }
                handle = generic;
            }
            return names.TryGetParent(handle, out targetAsm, out type);
        }
    }

    private static void WriteFeature(string path, string title, List<string> lines)
    {
        const string Begin = "<!-- api:begin -->", End = "<!-- api:end -->";
        var sb = new StringBuilder();
        sb.AppendLine(Begin);
        sb.AppendLine("<!-- Generated from the compiled module by Pandaborn.ApiScan on every build. Do not edit by hand. -->");
        sb.AppendLine();
        sb.AppendLine("### Game API this module references");
        sb.AppendLine();
        var specs = lines.Where(l => l[0] == 'D').Select(l => l.Split('\t')[1]).ToList();
        if (specs.Count > 0) sb.AppendLine("Spec classes defined: " + string.Join(", ", specs.Select(s => "`" + s + "`")) + "\n");
        foreach (var group in lines.Where(l => l[0] == 'T' || l[0] == 'M' || l[0] == 'F').Select(l => l.Split('\t')).GroupBy(p => p[1]).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            sb.AppendLine("**" + group.Key + "**");
            sb.AppendLine();
            foreach (var p in group.OrderBy(p => p[2], StringComparer.Ordinal).ThenBy(p => p[0] == "T" ? 0 : 1).ThenBy(p => string.Join("\t", p), StringComparer.Ordinal))
            {
                if (p[0] == "T") sb.AppendLine("* type `" + p[2] + "`");
                else if (p[0] == "F") sb.AppendLine("  * field `" + p[3] + "`: `" + p[4] + "`");
                else sb.AppendLine("  * method `" + p[3] + (p[4] != "0" ? "<" + p[4] + ">" : "") + "(" + p[5].Replace(";", ", ") + ")`"
                                   + (p[6] != "System.Void" ? ": `" + p[6] + "`" : ""));
            }
            sb.AppendLine();
        }
        var bases = lines.Where(l => l[0] == 'V').Select(l => l.Split('\t')).ToList();
        if (bases.Count > 0)
        {
            sb.AppendLine("**Game classes derived from and interfaces implemented** (with the abstract members each had at build time; a new one keeps the module from loading)");
            sb.AppendLine();
            foreach (var p in bases.OrderBy(p => p[2], StringComparer.Ordinal).ThenBy(p => p[3], StringComparer.Ordinal))
            {
                var members = p[4].Length == 0 ? new string[0] : p[4].Split('|');
                sb.AppendLine("* " + (p[3] == "I" ? "interface" : "class") + " `" + p[2] + "`"
                              + (members.Length > 0 ? ": " + string.Join(", ", members.Select(m => "`" + m.Split('~')[0] + "`").Distinct()) : ""));
            }
            sb.AppendLine();
        }
        sb.Append(End);
        string block = sb.ToString().Replace("\r\n", "\n");
        string text = File.Exists(path) ? File.ReadAllText(path).Replace("\r\n", "\n") : "# " + title + "\n\n(What this module does, its data, and how it fails safely. Hand-written; the section below is generated.)\n\n";
        int b = text.IndexOf(Begin, StringComparison.Ordinal), e = text.IndexOf(End, StringComparison.Ordinal);
        text = b >= 0 && e > b ? text.Substring(0, b) + block + text.Substring(e + End.Length) : text.TrimEnd('\n') + "\n\n" + block + "\n";
        WriteIfChanged(path, text);
    }

    private sealed class Names
    {
        private readonly MetadataReader _md;
        public Names(MetadataReader md) { _md = md; }

        public string AssemblyOf(TypeReferenceHandle h)
        {
            var r = _md.GetTypeReference(h);
            while (r.ResolutionScope.Kind == HandleKind.TypeReference) r = _md.GetTypeReference((TypeReferenceHandle)r.ResolutionScope);
            if (r.ResolutionScope.Kind != HandleKind.AssemblyReference) return null;
            return _md.GetString(_md.GetAssemblyReference((AssemblyReferenceHandle)r.ResolutionScope).Name);
        }

        public string TypeRefName(TypeReferenceHandle h)
        {
            var r = _md.GetTypeReference(h);
            string name = _md.GetString(r.Name);
            if (r.ResolutionScope.Kind == HandleKind.TypeReference) return TypeRefName((TypeReferenceHandle)r.ResolutionScope) + "+" + name;
            string ns = _md.GetString(r.Namespace);
            return ns.Length > 0 ? ns + "." + name : name;
        }

        public string TypeDefName(TypeDefinitionHandle h)
        {
            var d = _md.GetTypeDefinition(h);
            string name = _md.GetString(d.Name);
            var outer = d.GetDeclaringType();
            if (!outer.IsNil) return TypeDefName(outer) + "+" + name;
            string ns = _md.GetString(d.Namespace);
            return ns.Length > 0 ? ns + "." + name : name;
        }

        /// <summary>The declaring type of a member reference: a type reference, or a generic instance of one.</summary>
        public bool TryGetParent(EntityHandle parent, out string asm, out string type)
        {
            asm = null; type = null;
            if (parent.IsNil) return false;
            if (parent.Kind == HandleKind.TypeReference)
            {
                var h = (TypeReferenceHandle)parent;
                asm = AssemblyOf(h); type = TypeRefName(h);
                return asm != null;
            }
            if (parent.Kind == HandleKind.TypeSpecification)
            {
                var spec = _md.GetTypeSpecification((TypeSpecificationHandle)parent);
                var reader = _md.GetBlobReader(spec.Signature);
                if (reader.ReadSignatureTypeCode() != SignatureTypeCode.GenericTypeInstance) return false;
                reader.ReadCompressedInteger();           // CLASS or VALUETYPE
                var generic = reader.ReadTypeHandle();
                if (generic.Kind != HandleKind.TypeReference) return false;
                var h = (TypeReferenceHandle)generic;
                asm = AssemblyOf(h); type = TypeRefName(h);
                return asm != null;
            }
            return false;
        }

        public bool IsComponentSpec(TypeDefinitionHandle h)
        {
            for (int depth = 0; depth < 32 && !h.IsNil; depth++)
            {
                var b = _md.GetTypeDefinition(h).BaseType;
                if (b.IsNil) return false;
                if (b.Kind == HandleKind.TypeReference)
                    return TypeRefName((TypeReferenceHandle)b) == "Timberborn.BlueprintSystem.ComponentSpec";
                if (b.Kind != HandleKind.TypeDefinition) return false;
                h = (TypeDefinitionHandle)b;
            }
            return false;
        }
    }

    /// <summary>Formats signature types the way Pandaborn.Bootstrap formats System.Type at runtime.</summary>
    private sealed class SignatureNames : ISignatureTypeProvider<string, object>
    {
        private readonly Names _names;
        public SignatureNames(Names names) { _names = names; }

        public string GetPrimitiveType(PrimitiveTypeCode typeCode) => typeCode switch
        {
            PrimitiveTypeCode.Boolean => "System.Boolean", PrimitiveTypeCode.Byte => "System.Byte", PrimitiveTypeCode.SByte => "System.SByte",
            PrimitiveTypeCode.Char => "System.Char", PrimitiveTypeCode.Int16 => "System.Int16", PrimitiveTypeCode.UInt16 => "System.UInt16",
            PrimitiveTypeCode.Int32 => "System.Int32", PrimitiveTypeCode.UInt32 => "System.UInt32", PrimitiveTypeCode.Int64 => "System.Int64",
            PrimitiveTypeCode.UInt64 => "System.UInt64", PrimitiveTypeCode.Single => "System.Single", PrimitiveTypeCode.Double => "System.Double",
            PrimitiveTypeCode.IntPtr => "System.IntPtr", PrimitiveTypeCode.UIntPtr => "System.UIntPtr", PrimitiveTypeCode.Object => "System.Object",
            PrimitiveTypeCode.String => "System.String", PrimitiveTypeCode.TypedReference => "System.TypedReference", PrimitiveTypeCode.Void => "System.Void",
            _ => typeCode.ToString()
        };

        public string GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind) => _names.TypeDefName(handle);
        public string GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind) => _names.TypeRefName(handle);
        public string GetTypeFromSpecification(MetadataReader reader, object context, TypeSpecificationHandle handle, byte rawTypeKind)
            => reader.GetTypeSpecification(handle).DecodeSignature(this, context);
        public string GetSZArrayType(string elementType) => elementType + "[]";
        public string GetArrayType(string elementType, ArrayShape shape) => elementType + "[" + new string(',', shape.Rank - 1) + "]";
        public string GetByReferenceType(string elementType) => elementType + "&";
        public string GetPointerType(string elementType) => elementType + "*";
        public string GetGenericInstantiation(string genericType, ImmutableArray<string> typeArguments) => genericType + "<" + string.Join(",", typeArguments) + ">";
        public string GetGenericTypeParameter(object context, int index) => "!" + index;
        public string GetGenericMethodParameter(object context, int index) => "!!" + index;
        public string GetModifiedType(string modifier, string unmodifiedType, bool isRequired) => unmodifiedType;
        public string GetPinnedType(string elementType) => elementType;
        public string GetFunctionPointerType(MethodSignature<string> signature) => "fnptr";
    }
}
