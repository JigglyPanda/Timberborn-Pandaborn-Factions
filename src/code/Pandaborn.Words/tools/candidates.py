"""Pandaborn.Words: list every vanilla enUS text that mentions beavers or kits, for hand review.

    python -I src/code/Pandaborn.Words/tools/candidates.py [--loc E:/PandabornDev/reference/Localizations] [--out FILE]
           [--check src/code/Pandaborn.Words/mod/Pandaborn/Words/words.enUS.txt]

Writes a TSV (key, vanilla text with newlines as \\n) of candidates. With --check, also compares the reviewed table
(words.enUS.txt) against the current vanilla texts: keys that no longer exist, keys whose vanilla text changed since the
table was reviewed (the table stores the vanilla text it was written against), and new candidates not yet reviewed.
Exit code 1 when --check finds anything, so a game update that changes a reviewed text is caught.

--lang zhCN (default enUS) does the same for another language: the vanilla texts are that language's files, the
review file is words.review.<lang>.txt, and the candidates are the texts matching that language's pattern (zhCN: every
text with the character for "beaver" compounds, which covers more lines than the English pattern does).
"""
import argparse
import csv
import glob
import os
import re
import sys

WORD = re.compile(r"\b(beaver|beavers|beaver's|beavers'|kit|kits|kit's|kits')\b", re.IGNORECASE)
# per language: what marks a text as speaking of beavers (zhCN: 狸, as in 海狸, 幼狸 and the puns the translators built on it)
WORDS = {"enUS": WORD, "zhCN": re.compile("狸")}
SKIP_KEYS = {"Beaver.NamePool"}


def load_vanilla(folder, lang="enUS"):
    texts = {}
    for path in sorted(glob.glob(os.path.join(folder, lang + "*.csv"))):
        name = os.path.basename(path)
        if name.startswith(lang + "_wip"):
            continue
        with open(path, encoding="utf-8-sig", newline="") as fh:
            for row in csv.reader(fh):
                if len(row) >= 2 and row[0] != "ID":
                    texts[row[0]] = row[1]
    return texts


def esc(text):
    return text.replace("\\", "\\\\").replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t")


def unesc(text):
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            n = text[i + 1]
            out.append({"n": "\n", "r": "\r", "t": "\t", "\\": "\\"}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def load_table(path):
    """Table lines: key TAB replacement TAB vanilla-text-it-was-reviewed-against  (optional leading @Feature TAB)."""
    entries = []
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#") or line.startswith("faction:"):
                continue
            parts = line.split("\t")
            feature = None
            if parts[0].startswith("@"):
                feature, parts = parts[0][1:], parts[1:]
            if len(parts) < 3:
                raise SystemExit(f"{path}:{n}: need key TAB replacement TAB vanilla")
            entries.append((feature, parts[0], unesc(parts[1]), unesc(parts[2]), n))
    return entries


# Keys the game reads through Phrase.New(...): a Phrase caches its text for the whole session, so swapping such a key
# would leak into the next game. None may be in the table.
PHRASE_KEYS = {"Beaver.Adulthood", "Bot.Durability", "Breeding.Progress", "Carrying.Carry", "Carrying.Good", "Work.MaxDepth",
               "Work.Productivity"}


def build(review, out, vanilla, lang="enUS"):
    lines, n_keys, problems = ["# Generated by tools/candidates.py --build from words.review.%s.txt. Do not edit." % lang,
                               "# KEY TAB replacement TAB vanilla text it was reviewed against (optional leading @Feature TAB)",
                               "faction: Inkpaws"], 0, 0
    with open(review, encoding="utf-8") as fh:
        for n, raw in enumerate(fh, 1):
            line = raw.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.split("\t")
            feature = parts.pop(0) if parts[0].startswith("@") else None
            if len(parts) != 2:
                print(f"{review}:{n}: need KEY TAB replacement")
                problems += 1
                continue
            key, text = parts
            if key not in vanilla:
                print(f"{review}:{n}: {key} is not a vanilla {lang} key")
                problems += 1
                continue
            if key in PHRASE_KEYS:
                print(f"{review}:{n}: {key} is read through a Phrase (cached for the session); it cannot be swapped")
                problems += 1
                continue
            # the review column already starts with "@": written once (two made Words.cs read the feature "@Ringtails",
            # which is never on, so feature lines never applied)
            lines.append(("@" + feature.lstrip("@") + "\t" if feature else "") + key + "\t" + text + "\t" + esc(vanilla[key]))
            n_keys += 1
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{n_keys} entries -> {out}" + (f"; {problems} problem(s)" if problems else ""))
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--loc", default=r"E:\PandabornDev\reference\Localizations")
    ap.add_argument("--out")
    ap.add_argument("--check")
    ap.add_argument("--lang", default="enUS", choices=sorted(WORDS), help="the language of the table (default enUS)")
    ap.add_argument("--review", help="default: words.review.<lang>.txt beside the module")
    ap.add_argument("--build", nargs=2, metavar=("REVIEW", "OUT"),
                    help="write the runtime table from the hand-reviewed file, adding each key's vanilla text")
    a = ap.parse_args()
    if not a.review:
        a.review = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "words.review.%s.txt" % a.lang)
    vanilla = load_vanilla(a.loc, a.lang)
    if a.build:
        return build(a.build[0], a.build[1], vanilla, a.lang)
    cands = {k: v for k, v in vanilla.items() if k not in SKIP_KEYS and WORDS[a.lang].search(v)}
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
            for k in sorted(cands):
                fh.write(f"{k}\t{esc(cands[k])}\n")
        print(f"{len(cands)} candidates -> {a.out}")
    if not a.check:
        if not a.out:
            for k in sorted(cands):
                print(f"{k}\t{esc(cands[k])}")
        return 0
    problems = 0
    reviewed = set()
    for feature, key, _, was, n in load_table(a.check):
        reviewed.add(key)
        if key not in vanilla:
            print(f"line {n}: {key} no longer exists in the game")
            problems += 1
        elif vanilla[key] != was:
            print(f"line {n}: {key} changed in the game; was {esc(was)!r}, now {esc(vanilla[key])!r}")
            problems += 1
    # keys reviewed and deliberately kept vanilla are listed as comments "# keep KEY ..."
    with open(a.review, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"#\s*keep\s+(\S+)", line)
            if m:
                reviewed.add(m.group(1))
    for k in sorted(set(cands) - reviewed):
        print(f"new candidate, not reviewed: {k}\t{esc(cands[k])}")
        problems += 1
    print(f"{len(cands)} candidates, {len(reviewed)} reviewed, {problems} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
