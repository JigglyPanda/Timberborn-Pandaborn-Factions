"""Store art: the Steam Workshop preview (the mod's thumbnail.png) and a square thumbnail, composed with Pillow only
from pictures that are already in the repository. No Blender, no game, nothing from outside the project.

What the game and the stores expect (checked 2026-11-25, game 1.1.2.8):
* The game's Steam Workshop uploader (`Timberborn.SteamWorkshopModUploadingUI.SteamWorkshopModThumbnail`) takes
  `thumbnail.png` (or .jpg/.jpeg) from the mod's root folder as the Workshop item's preview picture; without one it
  uploads its own default. Nothing else in the game reads the file (the in-game mod list shows no pictures).
* The official example mods ship a 960 x 540 thumbnail.png; the owner's Reskin ships 1280 x 720. Both are 16:9. Steam
  refuses preview files of 1 MB or more, so the PNG is kept well under that (the script fails above 950 KB).
* Steam shows the preview cropped to a square in its listings, so everything that matters sits in the middle
  720 x 720. mod.io wants a 16:9 logo of at least 512 x 288: the same file serves.

Ingredients, all AI-generated by this project's own lanes and all in the repo:
* the dusk village under the rising Sky Lantern: `Sprites/Pandaborn/WonderCompletion/wonder-completion-inkpaws.png`
  (a render of the mod's own models; the sky is continued upwards here with painted stars and lanterns),
* the avatar plates of the Inkpaw, the Ringtail and the Wooden Ox: `Sprites/Pandaborn/Avatars/`,
* the faction logo (the paw print in its rounded diamond), drawn at full size by `logo.py`,
* banner decals: `Materials/Pandaborn/Decals/Banners/`.
The only writing is the mod's title, in a plain font. No writing of any script appears in any texture.

usage (venv python): python -I src/pipeline/icons/store.py [--mod DIR] [--out DIR] [--no-mod]
  writes <out>/workshop_preview_1280x720.png and <out>/thumbnail_square_1024.png (default out: art/store) and copies
  the first to <mod>/thumbnail.png (unless --no-mod)
"""
import argparse
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np  # noqa: E402
from PIL import Image, ImageDraw, ImageFilter, ImageFont  # noqa: E402

import ink  # noqa: E402
import logo  # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
TITLE = "Pandaborn - Factions"
CREAM = (238, 226, 196)
GREEN = (132, 214, 160)            # the faction logo's bamboo green
NIGHT_TOP = np.array([17, 19, 44], float)
LANTERN = np.array([255, 150, 60], float)
MAX_BYTES = 950_000


def _font(size):
    for f in ("segoeuib.ttf", "arialbd.ttf", "DejaVuSans-Bold.ttf"):
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            continue
    return ImageFont.load_default()


def logo_image(px):
    """The shipped logo (logo.logo_paw) drawn at `px` pixels instead of the game's 98."""
    k = px / 98.0
    st = ink.Style("logo-big", canvas=px, extent=66 * k, extent_tall=66 * k, pen=6.0 * k, ink=GREEN,
                   shadow_dy=1.0 * k, shadow_grow=0.5 * k, shadow_blur=1.0 * k, shadow_alpha=0.45)
    c = ink.Icon(name="InkpawsLogo")
    logo.logo_paw(c)
    return ink.render(c, st)


def village(mod):
    return Image.open(os.path.join(mod, "Sprites", "Pandaborn", "WonderCompletion",
                                   "wonder-completion-inkpaws.png")).convert("RGB")


def backdrop(mod, W, H, strip_h, focus=0.5, seed=7):
    """Night sky over the dusk village: the wonder picture across the bottom (`strip_h` high, cropped round `focus`
    of its width), its sky continued to the top of the frame, stars, and paper lanterns drifting up."""
    v = village(mod)
    s = strip_h / v.height
    v = v.resize((max(W, int(round(v.width * s))), strip_h), Image.LANCZOS)
    x0 = int(round((v.width - W) * focus))
    v = v.crop((x0, 0, x0 + W, strip_h))
    va = np.asarray(v, float)
    sky_h = H - strip_h
    join = va[:6].mean(axis=(0, 1))                                  # the picture's own top colour
    t = (np.arange(sky_h) / max(1, sky_h - 1))[:, None, None] ** 1.25
    sky = NIGHT_TOP + (join - NIGHT_TOP) * t
    sky = np.broadcast_to(sky, (sky_h, W, 3)).copy()
    out = np.vstack([sky, va])
    blend = 26                                                       # no seam where the painted sky meets the picture
    for k in range(blend):
        a = k / blend
        out[sky_h + k] = va[k] * a + join * (1 - a)
    img = Image.fromarray(out.round().clip(0, 255).astype(np.uint8), "RGB")
    rng = np.random.default_rng(seed)
    d = ImageDraw.Draw(img, "RGBA")
    for _ in range(int(W * sky_h / 2600)):                           # stars, thinning towards the horizon
        x, y = rng.random() * W, (rng.random() ** 1.6) * (sky_h + 30)
        r = 0.6 + rng.random() ** 3 * 1.3
        a = int(70 + rng.random() * 150)
        d.ellipse([x - r, y - r, x + r, y + r], fill=(235, 232, 255, a))
    glow = Image.new("RGB", (W, H), (0, 0, 0))                       # lanterns: a soft glow under a small bright body
    body = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    gd, bd = ImageDraw.Draw(glow), ImageDraw.Draw(body)
    n = int(W / 26)
    for _ in range(n):
        x = rng.random() * W
        y = sky_h * (0.18 + 0.82 * rng.random() ** 0.7)
        r = 2.2 + 5.0 * (y / sky_h) ** 2 * rng.random()
        gd.ellipse([x - r * 3.2, y - r * 3.2, x + r * 3.2, y + r * 3.2], fill=(120, 58, 16))
        bd.ellipse([x - r * 0.8, y - r, x + r * 0.8, y + r], fill=(255, 168, 78, 235))
    glow = glow.filter(ImageFilter.GaussianBlur(7))
    img = Image.fromarray(np.clip(np.asarray(img, float) + np.asarray(glow, float) * 0.75, 0, 255).astype(np.uint8))
    img.paste(body, (0, 0), body)
    return img


def shadowed(layer, blur=10, alpha=0.6, dy=6):
    """The layer with a soft dark shadow under it (RGBA in, RGBA out, same size)."""
    a = layer.split()[3]
    sh = Image.new("RGBA", layer.size, (0, 0, 0, 0))
    sh.paste((6, 8, 20, 255), (0, dy), a)
    sh = sh.filter(ImageFilter.GaussianBlur(blur))
    sh.putalpha(sh.split()[3].point(lambda v: int(v * alpha)))
    sh.alpha_composite(layer)
    return sh


def paste(img, layer, x, y, **kw):
    pad = 40
    big = Image.new("RGBA", (layer.width + 2 * pad, layer.height + 2 * pad), (0, 0, 0, 0))
    big.paste(layer, (pad, pad))
    big = shadowed(big, **kw)
    img.paste(big, (int(x) - pad, int(y) - pad), big)


def plate(mod, name, px):
    return Image.open(os.path.join(mod, "Sprites", "Pandaborn", "Avatars", name + ".png")).convert("RGBA") \
        .resize((px, px), Image.LANCZOS)


def banner(mod, name, px):
    """A banner decal as a little cloth hanging from a bamboo rod."""
    b = Image.open(os.path.join(mod, "Materials", "Pandaborn", "Decals", "Banners", "PandabornBanner%s.png" % name)) \
        .convert("RGBA").resize((px, px), Image.LANCZOS)
    out = Image.new("RGBA", (px + 16, px + 12), (0, 0, 0, 0))
    out.paste(b, (8, 10))
    d = ImageDraw.Draw(out)
    d.rounded_rectangle([0, 3, px + 15, 11], 4, fill=(176, 150, 96, 255), outline=(70, 56, 34, 255))
    return out


def title_block(img, cx, y, logo_px, font_px):
    """The logo and the title on one line, centred on cx."""
    lg = logo_image(logo_px)
    f = _font(font_px)
    d = ImageDraw.Draw(img)
    tw = d.textlength(TITLE, font=f)
    gap = int(logo_px * 0.16)
    x = int(cx - (logo_px + gap + tw) / 2)
    txt = Image.new("RGBA", (int(tw) + 8, int(font_px * 1.5)), (0, 0, 0, 0))
    ImageDraw.Draw(txt).text((2, int(font_px * 0.1)), TITLE, font=f, fill=CREAM + (255,))
    paste(img, lg, x, y, blur=8, alpha=0.7, dy=3)
    paste(img, txt, x + logo_px + gap, y + (logo_px - txt.height) // 2, blur=6, alpha=0.85, dy=3)


def workshop_preview(mod):
    W, H = 1280, 720
    img = backdrop(mod, W, H, strip_h=294, focus=0.5)
    title_block(img, W / 2, 34, 92, 54)                              # title and plates inside the middle 720 px:
    px, gap = 224, 18                                                # Steam crops the preview to a square
    x0 = (W - (3 * px + 2 * gap)) // 2
    for k, name in enumerate(("InkpawsAdult", "RingtailAdult", "InkpawsBot")):
        paste(img, plate(mod, name, px), x0 + k * (px + gap), 176, blur=12, alpha=0.65, dy=8)
    for name, x, y in (("Paw", 34, 150), ("Bamboo", 150, 196), ("Moon", 1002, 196), ("Lantern", 1118, 150)):
        paste(img, banner(mod, name, 112), x, y, blur=7, alpha=0.55, dy=5)     # the banners in the margins
    return img


def square(mod):
    S = 1024
    img = backdrop(mod, S, S, strip_h=400, focus=0.5, seed=11)
    lg = logo_image(220)
    paste(img, lg, (S - 220) // 2, 28, blur=10, alpha=0.7, dy=4)
    f = _font(78)
    d = ImageDraw.Draw(img)
    tw = d.textlength(TITLE, font=f)
    txt = Image.new("RGBA", (int(tw) + 8, 118), (0, 0, 0, 0))
    ImageDraw.Draw(txt).text((2, 8), TITLE, font=f, fill=CREAM + (255,))
    paste(img, txt, (S - txt.width) // 2, 246, blur=7, alpha=0.85, dy=4)
    px, gap = 262, 30
    x0 = (S - (3 * px + 2 * gap)) // 2
    for k, name in enumerate(("InkpawsAdult", "RingtailAdult", "InkpawsBot")):
        paste(img, plate(mod, name, px), x0 + k * (px + gap), 372, blur=12, alpha=0.65, dy=8)
    return img


def save(img, path):
    img = img.convert("RGB")
    img.save(path, optimize=True)
    if os.path.getsize(path) > MAX_BYTES:                            # Steam's limit is 1 MB: fewer colours, same picture
        img.quantize(colors=255, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG) \
            .save(path, optimize=True)
    n = os.path.getsize(path)
    print("%s  %dx%d  %d KB" % (path, img.width, img.height, n // 1024))
    if n > MAX_BYTES:
        raise SystemExit("%s is over %d KB (Steam refuses 1 MB)" % (path, MAX_BYTES // 1000))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mod", default=os.path.join(REPO, "mod", "PandabornFactions"))
    ap.add_argument("--out", default=os.path.join(REPO, "art", "store"))
    ap.add_argument("--no-mod", action="store_true")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    wp = os.path.join(a.out, "workshop_preview_1280x720.png")
    save(workshop_preview(a.mod), wp)
    save(square(a.mod), os.path.join(a.out, "thumbnail_square_1024.png"))
    if not a.no_mod:
        shutil.copyfile(wp, os.path.join(a.mod, "thumbnail.png"))
        print("copied to", os.path.join(a.mod, "thumbnail.png"))


if __name__ == "__main__":
    main()
